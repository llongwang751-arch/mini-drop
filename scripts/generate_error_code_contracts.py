"""Generate ErrorCode bindings and Proto enum from one contract."""

from __future__ import annotations

import argparse
import json
import pprint
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "contracts" / "error-codes.json"
NAME = re.compile(r"^[A-Z][A-Z0-9_]*$")


def _load() -> dict:
    payload = json.loads(SOURCE.read_text(encoding="utf-8"))
    items = payload.get("codes") or []
    ids = [int(item["id"]) for item in items]
    names = [str(item["name"]) for item in items]
    if not items or items[0] != next((item for item in items if item["id"] == 0), None):
        raise ValueError("ErrorCode id 0 must be the first item")
    if len(ids) != len(set(ids)) or len(names) != len(set(names)):
        raise ValueError("ErrorCode ids and names must be unique")
    if any(NAME.fullmatch(name) is None for name in names):
        raise ValueError("invalid ErrorCode name")
    return payload


def _proto(payload: dict) -> str:
    rows = "\n".join(
        f"  ERROR_CODE_{item['name']} = {item['id']};" for item in payload["codes"]
    )
    return f'''// Code generated by scripts/generate_error_code_contracts.py; DO NOT EDIT.
syntax = "proto3";
package mini_drop;
option go_package = "github.com/jiangyulin1/mini-drop/proto;mini_drop";

enum ErrorCode {{
{rows}
}}
'''


def _python(payload: dict) -> str:
    rows = "\n".join(f'    {item["name"]} = "{item["name"]}"' for item in payload["codes"])
    by_name = {item["name"]: item for item in payload["codes"]}
    rendered_by_name = pprint.pformat(by_name, width=100, sort_dicts=False)
    return f'''# Code generated by scripts/generate_error_code_contracts.py; DO NOT EDIT.
from enum import Enum, unique

@unique
class ErrorCode(str, Enum):
{rows}

BY_NAME = {rendered_by_name}
BY_ID = {{int(item["id"]): item for item in BY_NAME.values()}}
'''


def _go(payload: dict) -> str:
    constants = "\n".join(
        f'\t{item["name"].title().replace("_", "")} Code = "{item["name"]}"'
        for item in payload["codes"]
    )
    rows = "\n".join(
        f'\t{item["name"].title().replace("_", "")}: {{ID: {item["id"]}, Phase: "{item["phase"]}", Retryable: {str(item["retryable"]).lower()}, GRPCCode: "{item["grpc_code"]}", UserMessageZH: "{item["user_message_zh"]}"}},'
        for item in payload["codes"]
    )
    return f'''// Code generated by scripts/generate_error_code_contracts.py; DO NOT EDIT.
package errorcode

type Code string
type Metadata struct {{ ID int; Phase string; Retryable bool; GRPCCode string; UserMessageZH string }}

const (
{constants}
)

var ByCode = map[Code]Metadata{{
{rows}
}}
'''


def _cpp(payload: dict) -> str:
    rows = "\n".join(
        f'  {{{item["id"]}, "{item["name"]}", "{item["phase"]}", {str(item["retryable"]).lower()}}},'
        for item in payload["codes"]
    )
    constants = "\n".join(
        f'inline constexpr std::string_view kError{item["name"].title().replace("_", "")} = "{item["name"]}";'
        for item in payload["codes"]
    )
    return f'''// Code generated by scripts/generate_error_code_contracts.py; DO NOT EDIT.
#pragma once
#include <array>
#include <string_view>
namespace mini_drop_contract {{
struct ErrorCodeContract {{ int id; std::string_view name; std::string_view phase; bool retryable; }};
inline constexpr std::array<ErrorCodeContract, {len(payload["codes"])}> kErrorCodes{{{{
{rows}
}}}};
{constants}
inline constexpr const ErrorCodeContract* find_error_code(std::string_view name) {{
  for (const auto& item : kErrorCodes) if (item.name == name) return &item;
  return nullptr;
}}
inline constexpr const ErrorCodeContract* find_error_code(int id) {{
  for (const auto& item : kErrorCodes) if (item.id == id) return &item;
  return nullptr;
}}
}}  // namespace mini_drop_contract
'''


def _javascript(payload: dict) -> str:
    return "// Code generated by scripts/generate_error_code_contracts.py; DO NOT EDIT.\nexport const ERROR_CODES = Object.freeze(" + json.dumps(payload, ensure_ascii=False, indent=2) + ");\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    payload = _load()
    outputs = {
        ROOT / "proto/errorcode.proto": _proto(payload),
        ROOT / "server/app/generated/error_code_contract.py": _python(payload),
        ROOT / "apiserver/internal/errorcode/codes.go": _go(payload),
        ROOT / "native/generated/error_code_contract.h": _cpp(payload),
        ROOT / "web/src/generated/errorCodes.js": _javascript(payload),
    }
    stale = []
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        raise SystemExit("stale generated ErrorCode contracts: " + ", ".join(stale))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
